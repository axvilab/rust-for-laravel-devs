//! Розіменування `*`: значення за посиланням

fn main() {
    let x = 10;
    let r = &x;
    println!("{}", r + 1); // ok: арифметика сама розіменовує
    let y: i32 = *r; // явно: взяти значення за посиланням
    println!("{y}");

    let mut count = 0;
    let c = &mut count;
    *c += 1; // змінити значення за змінним посиланням
    println!("{count}"); // 1

    let s = String::from("текст");
    let rs = &s;
    println!("{}", rs.len()); // у викликах методів зірочка не потрібна
}
