//! Або багато `&`, або один `&mut`; позичання закінчується на останньому використанні

fn main() {
    let mut list = vec![1, 2, 3];

    let a = &list;
    let b = &list; // ok: два читачі
    println!("{a:?} {b:?}");

    let c = &mut list; // ok: читачі a, b більше не використовуються
    c.push(4);
    c.push(5); // c використовується востаннє тут

    let d = &list; // ok: редактор c уже «повернув» доступ
    println!("{d:?}"); // [1, 2, 3, 4, 5]
}
