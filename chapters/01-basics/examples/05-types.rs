//! Виведення типів і явна анотація

fn main() {
    let a = 5; // i32 (ціле зі знаком, 32 біти)
    let b = 5.0; // f64 (дробове, 64 біти)
    let c = true; // bool
    let d = 'x'; // char — один символ Unicode, в одинарних лапках
    let e = "текст"; // &str — рядок

    let port: u16 = 8080; // тип вказано явно

    println!("{a} {b} {c} {d} {e} {port}");
}
